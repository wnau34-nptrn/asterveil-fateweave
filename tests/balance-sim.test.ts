import { writeFileSync, mkdirSync } from 'node:fs';
import { describe, expect, it } from 'vitest';
import { report, simulateCompany, type CompanyReport } from './sim/balance-sim';

// Phase 4E. `npm run sim` writes the full report (docs/validation/balance-sim/REPORT.md); the normal test run
// keeps a small sweep as a regression guard on the draft numbers.
const full = process.env.SIM_REPORT === '1';
const seeds = full ? Array.from({ length: 24 }, (_, i) => 1001 + i * 37) : [1001, 1038, 1075];
const expeditions = full ? 6 : 3;

describe('whole-map balance simulation', () => {
  const companies: CompanyReport[] = [];
  for (const seed of seeds) {
    companies.push(simulateCompany(seed, 'rush', expeditions), simulateCompany(seed, 'explorer', expeditions));
    if (full) companies.push(simulateCompany(seed, 'rush', expeditions, 'casual'), simulateCompany(seed, 'explorer', expeditions, 'casual'), simulateCompany(seed, 'explorer', expeditions, 'attack'));
  }
  it('is deterministic for a seed', () => {
    expect(JSON.stringify(simulateCompany(seeds[0]!, 'explorer', expeditions))).toBe(JSON.stringify(companies.find(c => c.policy === 'explorer' && c.seed === seeds[0])));
  });
  it('a careful player finishes the chapter within a few expeditions and wipes rarely', () => {
    for (const policy of ['rush', 'explorer'] as const) {
      const cs = companies.filter(c => c.policy === policy && c.style === 'advisor'); const all = cs.flatMap(c => c.expeditions);
      expect(cs.every(c => c.expeditions.some(e => e.outcome === 'complete'))).toBe(true);
      expect(all.filter(e => e.outcome === 'wiped').length / all.length).toBeLessThan(0.34);
    }
  });
  it('exploring pays: more chests, items and side-quest progress than rushing', () => {
    const sum = (policy: string, f: (e: CompanyReport['expeditions'][number]) => number) => companies.filter(c => c.policy === policy && c.style === 'advisor').flatMap(c => c.expeditions).reduce((a, e) => a + f(e), 0);
    expect(sum('explorer', e => e.chests)).toBeGreaterThan(sum('rush', e => e.chests));
    expect(sum('explorer', e => e.gained.ore)).toBeGreaterThan(sum('rush', e => e.gained.ore));
    // Every chest and puzzle on the map can be reached (the explorer opens all of them), and side quests get claimed.
    expect(companies.filter(c => c.policy === 'explorer' && c.style === 'advisor').every(c => c.expeditions.some(e => e.chests === 12))).toBe(true);
    expect(companies.filter(c => c.policy === 'explorer' && c.style === 'advisor').some(c => c.expeditions.some(e => e.claimed.length))).toBe(true);
  });
  if (full) it('writes the report', () => {
    mkdirSync('docs/validation/balance-sim', { recursive: true });
    writeFileSync('docs/validation/balance-sim/REPORT.md', `# Balance simulation (4E)\n\nGenerated by \`npm run sim\` (tests/sim/balance-sim.ts). Battles are played by the teaching advisor.\n\n${report(companies)}`);
  });
});
