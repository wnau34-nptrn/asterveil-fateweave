import { mkdirSync, writeFileSync } from 'node:fs';
import { describe, expect, it } from 'vitest';
import { classReport, classSim } from './sim/class-sim';

// Stats design step 5 (docs/STATS_DESIGN.md): every class gains from gear, and more from its own main stats than
// from stats it barely uses. `npm run sim` also writes docs/validation/balance-sim/CLASSES.md.
describe('per-class gear simulation', () => {
  const rows = classSim(11);
  const row = (id: string, build: string) => rows.find(r => r.id === id && r.build === build)!;
  const hp = (id: string, build: string) => row(id, build).partyHp / row(id, build).fought;
  const ids = [...new Set(rows.map(r => r.id))];
  it('gear always helps, and main-stat gear is never worse for the party than off-stat gear', () => {
    expect(ids.length).toBeGreaterThan(0);
    for (const id of ids) {
      expect(hp(id, 'main'), id).toBeGreaterThan(hp(id, 'none'));
      expect(hp(id, 'main'), id).toBeGreaterThanOrEqual(hp(id, 'off') - 0.005);
    }
    // Most classes see a real difference between their own stats and the others.
    expect(ids.filter(id => hp(id, 'main') > hp(id, 'off') || row(id, 'main').dealt + row(id, 'main').healed > row(id, 'off').dealt + row(id, 'off').healed).length).toBeGreaterThanOrEqual(Math.ceil(ids.length*.8));
  });
  if (process.env.SIM_REPORT === '1') it('writes the report', () => {
    mkdirSync('docs/validation/balance-sim', { recursive: true });
    writeFileSync('docs/validation/balance-sim/CLASSES.md', `# Per-class gear simulation (stats design step 5)\n\nGenerated by \`npm run sim\` (tests/sim/class-sim.ts). Each class (★3 Lv6) fights six mid-game encounters at fight level 11 with three teaching members, played by the teaching advisor:\n\n| Build | Gear |\n|---|---|\n| none | no gear |\n| main | epic Lv11 gear rolled on its main stats |\n| off | the same pieces rolled on stats it barely uses |\n\nDealt, Healed and Taken are that class's own totals.\n\n${classReport(rows)}\n`);
  });
});
