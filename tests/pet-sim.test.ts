import { mkdirSync, writeFileSync } from 'node:fs';
import { expect, it } from 'vitest';
import { hooks, playExpedition, simulateCampaign, type CampaignReport } from './sim/balance-sim';
import { MAPS } from '../src/content/world/maps';
import { lakeMap } from '../src/content/world/chapter-lake';
import { mineMap } from '../src/content/world/chapter-mine';
import type { ExpeditionState, MapDefinition, PetKind, Profile } from '../src/core/world/types';

// PET-2 (OD-63): each map blessing against no pet. Companies play the campaign maps 1 → 4 (story order, no replays), then
// the same lake replay and the first mine try are played once with no pet and once with each pet at Lv1 and Lv6 (same
// expedition seeds, so differences come from the blessing and the rolls it moves). `npm run sim` writes
// docs/validation/pets/PET2_SIM.md; the normal run keeps one company as a smoke check.
const full = process.env.SIM_REPORT === '1';
const companies: CampaignReport[] = (full ? [1001, 1038, 1075, 1112] : [1001]).map(seed => simulateCampaign(seed, 'rush', 'advisor', 0, 0, 12, undefined, MAPS.filter(m => m.chapter <= lakeMap.chapter)));
const tries = full ? 6 : 1;
const variants: { label: string; kind?: PetKind; level: number }[] = [{ label: 'ไม่มีสัตว์', level: 1 },
  ...lakeMap.pets.kinds.flatMap(k => [1, 6].map(level => ({ label: `${k.blessing.kind} Lv${level}`, kind: k.id, level })))]
  .filter(v => full || ['ไม่มีสัตว์', 'ward Lv6', 'forage Lv6'].includes(v.label));
const withPet = (p: Profile, kind: PetKind | undefined, level: number): Profile =>
  ({ ...structuredClone(p), pets: { eggs: 0, shards: 0, owned: kind ? [{ kind, level, exp: 0 }] : [], ...(kind ? { chosen: kind } : {}), from: [] } });
interface Row { runs: number; complete: number; steps: number; random: number; hpIn: number; fights: number; ore: number; gold: number; shard: number; fog: number }
const blank = (): Row => ({ runs: 0, complete: 0, steps: 0, random: 0, hpIn: 0, fights: 0, ore: 0, gold: 0, shard: 0, fog: 0 });
const fogShare = (s: ExpeditionState) => [...s.revealed].filter(c => c === '1').length / s.revealed.length;

function play(map: MapDefinition): Map<string, Row> {
  const rows = new Map(variants.map(v => [v.label, blank()]));
  for (const c of companies) for (let t = 0; t < tries; t++) for (const v of variants) {
    const row = rows.get(v.label)!; const seed = (c.seed * 31 + t * 7919) >>> 0;
    hooks.battle = (_s, label, _won, before) => { if (label === 'random') { row.random++; row.hpIn += before; } row.fights++; };
    const r = playExpedition(withPet(c.profile, v.kind, v.level), map, false, 'explorer', 'advisor', seed, 1);
    delete hooks.battle;
    row.runs++; if (r.outcome === 'complete') row.complete++; row.steps += r.run.steps; row.fog += fogShare(r.run);
    row.ore += r.gained.ore; row.gold += r.gained.gold; row.shard += r.gained.shard;
  }
  return rows;
}
const lake = play(lakeMap); const mine = full ? play(mineMap) : new Map<string, Row>();

it('every blessing keeps the run playable and changes something only in its own lane', () => {
  for (const [label, r] of lake) expect(r.runs, label).toBe(companies.length * tries);
  const none = lake.get('ไม่มีสัตว์')!; const ward = lake.get('ward Lv6')!; const moth = lake.get('farsight Lv1')!; const pig = lake.get('forage Lv6')!;
  if (full) {
    expect(ward.random / ward.runs).toBeLessThanOrEqual(none.random / none.runs);
    expect(moth.fog / moth.runs).toBeGreaterThan(none.fog / none.runs);
    expect(pig.ore / pig.runs).toBeGreaterThan(none.ore / none.runs);
  }
});
if (full) it('writes the PET-2 map report', () => {
  const f = (n: number, d: number, digits = 1) => d ? (n / d).toFixed(digits) : '–';
  const table = (title: string, rows: Map<string, Row>) => {
    const none = rows.get('ไม่มีสัตว์')!; const d = (a: number, b: number) => { const x = a - b; return `${x >= 0 ? '+' : ''}${x.toFixed(1)}`; };
    return [`## ${title}`, '', '| Pet | Runs | Complete | Steps | Random fights (vs none) | HP% entering random fights | All fights | Ore (vs none) | Gold | Shards | Fog opened |', '|---|---|---|---|---|---|---|---|---|---|---|',
      ...[...rows].map(([label, r]) => `| ${label} | ${r.runs} | ${Math.round(r.complete / r.runs * 100)}% | ${f(r.steps, r.runs, 0)} | ${f(r.random, r.runs)} (${d(r.random / r.runs, none.random / none.runs)}) | ${f(r.hpIn, r.random, 0)} | ${f(r.fights, r.runs)} | ${f(r.ore, r.runs)} (${d(r.ore / r.runs, none.ore / none.runs)}) | ${f(r.gold, r.runs)} | ${f(r.shard, r.runs)} | ${Math.round(r.fog / r.runs * 100)}% |`), ''].join('\n');
  };
  mkdirSync('docs/validation/pets', { recursive: true });
  writeFileSync('docs/validation/pets/PET2_SIM.md', `# PET-2 map blessings — simulation\n\nGenerated by \`npm run sim\` (tests/pet-sim.test.ts). ${companies.length} companies (advisor, rush) play maps 1 → 4 in story order; then each plays ${tries} lake replays and ${tries} first mine tries (explorer policy, same seeds) with no pet and with each pet at Lv1/Lv6. The scripted player walks its own route and does not read the fog, so farsight/lantern show as fog opened only (lantern adds sightings, not fog). Numbers per run.\n\n${table('Map 4 ทะเลสาบเงาจันทร์ (replay)', lake)}\n${table('Map 5 เหมืองผลึกร้าง (first try)', mine)}`);
});
