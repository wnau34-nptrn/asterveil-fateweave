import { mkdirSync, writeFileSync } from 'node:fs';
import { describe, expect, it } from 'vitest';
import { chapterOne as map } from '../src/content/world/chapter1';
import { talentsValid } from '../src/core/world/talents';
import { encounterById as lookup } from '../src/content/encounters/catalog';
import { beginBattle, withParty } from '../src/core/battle/engine';
import { heroCatalog, starred } from '../src/core/world/world';
import { battleLesson } from '../src/ui/tutorial';
import { TREE_BUILDS, TREE_LEVEL, TREE_STARS, treeReport, treeSim } from './sim/tree-sim';

// Release A big trees: the example builds of docs/design/SKILL_TREES_ALL_TH.md are legal at ★3 Lv10, the advisor uses
// their tree skills, and each keeps a winning route. `npm run sim` writes docs/validation/balance-sim/TREES.md.
describe('release A tree builds', () => {
  it('every example build is a legal tree at ★3 Lv10', () => {
    for (const b of TREE_BUILDS) expect(talentsValid(map, b.id, TREE_LEVEL, b.talents, TREE_STARS), `${b.id} ${b.name}`).toBe(true);
  });
  const rows = treeSim();
  it('the advisor wins with every build and uses its tree skills', () => {
    for (const r of rows) expect(r.won, `${r.id} ${r.build}`).toBeGreaterThanOrEqual(r.fought - 2);
    // Revive waits for a fall, so at least two of each class's three builds use their tree skills in these fights.
    for (const id of new Set(rows.map(r => r.id))) expect(rows.filter(r => r.id === id && r.used > 0).length, id).toBeGreaterThanOrEqual(2);
  });
  it('the advisor revives a fallen ally when the priest has revive equipped', () => {
    const data = withParty(lookup('thicket-ambush')!, heroCatalog(lookup, map).slice(0, 4).map(h => h.id === 'healer' ? starred(h, 3, map, 10, { a1: 2, a2t: 1, a3: 1 }, undefined, { loadout: ['revive', 'heal', 'prayer'] }) : starred(h, 3, map, 10)));
    const s = structuredClone(beginBattle(data).state); s.turnIndex = s.order.indexOf('healer');
    const lyra = s.heroes.find(h => h.id === 'tracer')!; lyra.hp = 0; lyra.fell = true;
    expect(battleLesson(s, data)).toMatchObject({ heroId: 'healer', action: 'revive', targetId: 'tracer' });
  });
  if (process.env.SIM_REPORT === '1') it('writes the report', () => {
    mkdirSync('docs/validation/balance-sim', { recursive: true });
    writeFileSync('docs/validation/balance-sim/TREES.md', `# Release A tree builds\n\nGenerated by \`npm run sim\` (tests/sim/tree-sim.ts). Each class (★3 Lv10) fights ten mid-game sets at fight level 15 with three teaching members (★3 Lv10, no tree points), played by the teaching advisor. "Tree skills used" counts the advisor's commands with skills the build unlocked.\n\n${treeReport(rows)}\n`);
  });
});
