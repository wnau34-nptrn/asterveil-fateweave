import { mkdirSync, writeFileSync } from 'node:fs';
import { describe, expect, it } from 'vitest';
import { campaignReport, simulateCampaign, type CampaignReport } from './sim/balance-sim';
import { MAPS } from '../src/content/world/maps';

// A10 (2026-10-22): a new company plays maps 1 → 2 → 3 with story recruits, example tree builds, formation and skill
// tomes, then replays veil-frontier and plays it on hard. `npm run sim` writes docs/validation/balance-sim/CAMPAIGN.md;
// the normal run keeps one seed per policy as a regression guard on the draft numbers.
const full = process.env.SIM_REPORT === '1';
const seeds = full ? Array.from({ length: 12 }, (_, i) => 1001 + i * 37) : [1001];
describe('campaign simulation (A10)', () => {
  const cs: CampaignReport[] = seeds.flatMap(seed => (full ? ['advisor', 'casual'] as const : ['advisor'] as const).flatMap(style => (['rush', 'explorer'] as const).map(policy => simulateCampaign(seed, policy, style))));
  const advisor = cs.filter(c => c.style === 'advisor');
  it('the advisor clears every map in order and reaches hard mode', () => {
    for (const c of advisor) {
      expect(MAPS.every(m => c.profile.cleared.includes(m.id)), `${c.seed} ${c.policy}`).toBe(true);
      expect(c.expeditions.some(e => e.hard), `${c.seed} ${c.policy}`).toBe(true);
    }
  });
  it('plain attacks lose the bosses and forced elites of maps 2 and 3 more often than not', () => {
    for (const label of ['boss', 'elite-forced']) {
      const st = advisor.flatMap(c => c.expeditions.filter(e => e.mapId !== MAPS[0]!.id && !e.hard)).map(e => e.battles[`${label}:attack`]).filter(Boolean);
      expect(st.reduce((a, b) => a + b!.won, 0) / st.reduce((a, b) => a + b!.fought, 0), label).toBeLessThan(0.8);
    }
  });
  it('skill tomes follow the pacing: Lv2–3 after the first veil-frontier clear, Lv5 only after hard mode', () => {
    for (const c of advisor) {
      // Paced for a company that clears veil-frontier at once (one whose first try failed has fewer wins behind it).
      const normal = c.expeditions.filter(e => e.mapId === 'veil-frontier' && !e.hard); const second = normal[1]!;
      if (normal[0]!.outcome === 'complete') { expect(second.mainSkill, `${c.seed} ${c.policy}`).toBeGreaterThanOrEqual(1.5); expect(second.mainSkill).toBeLessThanOrEqual(3.5); }
      const five = c.expeditions.find(e => e.topSkill >= 5); if (five) expect(c.expeditions.some(e => e.hard && e.index < five.index && e.bossBeaten), `${c.seed} ${c.policy}`).toBe(true);
    }
  });
  if (full) it('writes the report', () => {
    mkdirSync('docs/validation/balance-sim', { recursive: true });
    writeFileSync('docs/validation/balance-sim/CAMPAIGN.md', `# Campaign simulation (A10)\n\nGenerated by \`npm run sim\` (tests/campaign-sim.test.ts, tests/sim/balance-sim.ts). A new company (the Knight alone, story recruits) plays ซากชายแดน → เส้นทางป่าทึบ → แนวรอยแยก, replays แนวรอยแยก three times and plays it twice on hard. Between expeditions it hires, upgrades, follows the first example tree build of each class (tests/sim/tree-sim.ts) with its skills equipped, raises equipped skills with tomes (main skill first, trading up when a bigger tome is needed, keeping 20 gold) before the market, and equips the best gear. Class lanes are the formation. Rows \`<battle>:attack\` replay the same elite or boss fight with blind basic attacks, \`boss:under2\` with the party two levels lower (advisor); neither changes the run.\n\n${campaignReport(cs)}`);
  });
});
