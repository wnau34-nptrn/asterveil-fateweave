import { writeFileSync, mkdirSync } from 'node:fs';
import { describe, expect, it } from 'vitest';
import { simulateCompany, type CompanyReport } from './sim/balance-sim';
import { formationReport, formationSim } from './sim/formation-sim';
import type { Lane } from '../src/core/world/types';

// Formation comparison (owner 2026-10-22): the same companies play the chapter with the class formation, 3 front /
// 1 back, 1 front / 3 back and knight ↔ mage swapped. `npm run sim` writes docs/validation/formation-sim/REPORT.md;
// the normal run keeps a small sweep that only checks the comparison runs and differs.
const full = process.env.SIM_REPORT === '1';
const seeds = full ? Array.from({ length: 12 }, (_, i) => 1001 + i * 37) : [1001];
const expeditions = full ? 4 : 2;
const FORMATIONS: [string, Record<string, Lane> | undefined][] = [
  ['class lanes 2/2 (knight, duelist front)', undefined],
  ['3/1: mage steps forward', { weaver: 'front' }],
  ['1/3: duelist steps back', { tracer: 'back' }],
  ['swap: mage front, knight back', { guardian: 'back', weaver: 'front' }],
];
describe('formation comparison', () => {
  const rows = FORMATIONS.map(([name, lanes]) => ({ name, cs: seeds.flatMap(seed => (['rush', 'explorer'] as const).map(policy => simulateCompany(seed, policy, expeditions, 'advisor', lanes))) }));
  const battles = formationSim(FORMATIONS);
  it('every formation keeps a winning route with the advisor', () => {
    for (const r of battles.filter(b => b.style === 'advisor')) expect(r.won, r.name).toBeGreaterThanOrEqual(r.fought - 2);
  });
  it('formations change outcomes', () => {
    expect(new Set(rows.map(r => JSON.stringify(r.cs.map(c => c.expeditions.map(e => [e.wins, e.defeats, e.lowestHp]))))).size).toBeGreaterThan(1);
  });
  if (full) it('writes the report', () => {
    const avg = (xs: number[]) => xs.length ? xs.reduce((a, b) => a + b, 0) / xs.length : 0;
    const line = (name: string, cs: CompanyReport[]) => {
      const es = cs.flatMap(c => c.expeditions); const st = es.flatMap(e => Object.values(e.battles).filter(Boolean)) as { fought: number; won: number; hpAfter: number; low: number }[];
      const fought = st.reduce((a, b) => a + b.fought, 0), won = st.reduce((a, b) => a + b.won, 0);
      const first = cs.map(c => c.expeditions.find(e => e.outcome === 'complete')?.index ?? expeditions + 1);
      return `| ${name} | ${Math.round(es.filter(e => e.outcome === 'complete').length / es.length * 100)}% | ${Math.round(es.filter(e => e.outcome === 'wiped').length / es.length * 100)}% | ${(won / fought * 100).toFixed(1)}% | ${Math.round(st.reduce((a, b) => a + b.low, 0) / fought)} | ${Math.round(st.reduce((a, b) => a + b.hpAfter, 0) / won)} | ${Math.round(avg(es.map(e => e.lowestHp)))} | ${avg(first).toFixed(2)} |`;
    };
    mkdirSync('docs/validation/formation-sim', { recursive: true });
    writeFileSync('docs/validation/formation-sim/REPORT.md', `# Formation comparison\n\nGenerated by \`npm run sim\` (tests/formation-sim.test.ts): ${seeds.length} seeds × rush/explorer × ${expeditions} expeditions per formation, advisor battles, starting company (Knight, Duelist, Mage, Priest).\n\n## Whole chapter 1\n\n| Formation | Complete | Wiped | Battles won | Lowest party HP% during (avg) | HP% after a win | Lowest HP% per expedition | First complete (avg exp.; ${expeditions + 1} = never) |\n|---|---|---|---|---|---|---|---|\n${rows.map(r => line(r.name, r.cs)).join('\n')}\n\n## Single battles at fight level 11 (★3 Lv6 party, ten mid-game sets)\n\n${formationReport(battles)}\n`);
  });
});
