import { mkdirSync, writeFileSync } from 'node:fs';
import { describe, expect, it } from 'vitest';
import { ruinsMap } from '../src/content/world/chapter-ruins';
import { simulateCampaign } from './sim/balance-sim';

// Starter recruitment (owner 2026-10-23): every pair a new company can recruit after the prologue (a support among
// them) must clear map 1 with the advisor. Rush and explorer companies, a few seeds per pair.
const { pool, support } = ruinsMap.draft!;
const pairs = pool.flatMap((a, i) => pool.slice(i + 1).map(b => [a, b])).filter(p => p.some(id => support.includes(id)));
const seeds = process.env.SIM_REPORT === '1' ? [11, 23, 37, 41, 59, 61] : [11, 23];
describe('starter pairs on map 1', () => {
  const rows = pairs.map(pair => {
    const runs = seeds.flatMap(seed => (['rush', 'explorer'] as const).map(policy => simulateCampaign(seed, policy, 'advisor', 0, 0, 3, pair).expeditions.filter(e => e.mapId === ruinsMap.id)));
    return { pair, runs };
  });
  it.each(rows.map(r => [r.pair.join('+'), r] as const))('%s clears map 1 within three expeditions', (_name, { runs }) => {
    for (const r of runs) expect(r.some(e => e.outcome === 'complete')).toBe(true);
  });
  if (process.env.SIM_REPORT === '1') it('writes the report', () => {
    const lines = rows.map(({ pair, runs }) => {
      const first = runs.map(r => r[0]!); const done = first.filter(e => e.outcome === 'complete').length; const wiped = first.filter(e => e.outcome === 'wiped').length;
      return `| ${pair.join(' + ')} | ${runs.length} | ${Math.round(done / first.length * 100)}% | ${Math.round(wiped / first.length * 100)}% | ${(runs.reduce((a, r) => a + r.findIndex(e => e.outcome === 'complete') + 1, 0) / runs.length).toFixed(1)} |`;
    });
    mkdirSync('docs/validation/balance-sim', { recursive: true });
    writeFileSync('docs/validation/balance-sim/STARTERS.md', ['# Starter pairs on map 1', '', 'Generated by `npm run sim` (tests/starter-sim.test.ts). A new company recruits each pair after the prologue and plays ซากชายแดน with advisor battles (rush and explorer, ' + seeds.length + ' seeds each). Aira comes back as the boss fight starts (reserve when the party is full).', '', '| Pair | Companies | First run complete | First run wiped | Expedition that clears (avg) |', '|---|---|---|---|---|', ...lines, ''].join('\n'));
  });
});
