import { mkdirSync, writeFileSync } from 'node:fs';
import { expect, it } from 'vitest';
import { lowStarReport, lowStarSim, type LowStarRow } from './sim/low-star-sim';

// P04-04 (OD-01): a ★1 member at the team's camp level still does its role. Runs only under `npm run sim` (SIM_REPORT=1);
// STRESS=1 writes the no-gear, camp −2 variant. Gate: the ★1 member clears as often as at ★5 (one seed of slack), never
// falls in the probe while ★5 stands, and keeps at least 55% of the ★5 output (stats alone give ★1/★5 ≈ 0.76–0.80).
const full = process.env.SIM_REPORT === '1', stress = process.env.STRESS === '1';
it.runIf(full)('a low-star member still does its role (P04-04)', () => {
  const seeds = Array.from({ length: 12 }, (_, i) => 1001 + i * 37);
  const rows = lowStarSim(seeds, process.env.ONLY?.split(','), stress);
  const out = `docs/validation/p04-04-2026-11-14/LOW_STAR${stress ? '_STRESS' : ''}.md`;
  mkdirSync(out.replace(/\/[^/]+$/, ''), { recursive: true });
  writeFileSync(out, `# Low-star members at camp level (P04-04)\n\nGenerated by tests/low-star-sim.test.ts (\`npm run sim\`${stress ? ', STRESS=1' : ''}). Seeds: ${seeds.length}. ${stress ? 'Stress: no gear, camp two levels under the map level; hard left out.' : 'Epic main-stat gear at the map camp level.'} Subject at ★1/★3/★5, four companions ★3, team of five.\n\n${lowStarReport(rows)}\n`);
  const at = (r: LowStarRow, s: number) => rows.find(x => x.id === r.id && x.stage === r.stage && x.stars === s)!;
  const output = (r: LowStarRow) => r.dealt + r.healed + r.shielded;
  for (const r of rows.filter(x => x.stars === 1)) {
    const five = at(r, 5), key = `${r.id} ${r.stage}`;
    expect(r.won, key).toBeGreaterThanOrEqual(five.won - 1);
    expect(r.downs, key).toBeLessThanOrEqual(five.downs);
    expect(output(r) / Math.max(1, output(five)), key).toBeGreaterThanOrEqual(.55);
  }
}, 3_600_000);
