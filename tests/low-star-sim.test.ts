import { mkdirSync, writeFileSync } from 'node:fs';
import { it } from 'vitest';
import { lowStarReport, lowStarSim } from './sim/low-star-sim';
const full = process.env.SIM_REPORT === '1';
it('low-star members at camp level (P04-04 report)', () => {
  const seeds = full ? Array.from({ length: 12 }, (_, i) => 1001 + i * 37) : [1001];
  const stress = process.env.STRESS === '1';
  const rows = lowStarSim(seeds, process.env.ONLY?.split(','), stress);
  const out = process.env.LOW_STAR_OUT ?? `docs/validation/p04-04-2026-11-14/LOW_STAR${stress ? '_STRESS' : ''}.md`;
  mkdirSync(out.replace(/\/[^/]+$/, ''), { recursive: true });
  writeFileSync(out, `# Low-star members at camp level (P04-04)\n\nGenerated by tests/low-star-sim.test.ts. Seeds: ${seeds.length}. ${stress ? 'Stress: no gear, camp two levels under the map level.' : 'Epic main-stat gear at the map camp level.'}\n\n${lowStarReport(rows)}\n`);
}, 3_600_000);
