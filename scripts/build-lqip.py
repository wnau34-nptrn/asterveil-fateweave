#!/usr/bin/env python3
"""Regenerate src/ui/lqip.generated.ts: ~32 px blurred placeholders (data URIs) of the big scene paintings (B4, 2026-11-21).

Run: python3 scripts/build-lqip.py   (needs Pillow). `v` = first 12 hex of the SHA-256 of the source file, so
tests/lqip.test.ts fails when a painting changes and the placeholder is stale. Source files are never modified."""
import base64, hashlib, io, os
from PIL import Image, ImageFilter

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SOURCES = [
    'assets/title/title_party.webp',
    'assets/lobby/lobby_bg.webp',
    'assets/art/ruins.webp', 'assets/art/battle_forest.webp', 'assets/art/battle_riftline.webp',
    'assets/story/story_awaken.webp', 'assets/story/story_rift.webp', 'assets/story/story_retreat.webp',
]
WIDTH = 32

rows = []
for rel in SOURCES:
    path = os.path.join(ROOT, 'public', rel)
    raw = open(path, 'rb').read()
    im = Image.open(io.BytesIO(raw)).convert('RGB')
    h = max(1, round(WIDTH * im.height / im.width))
    # Box-average down first (true colours of the region), then a light blur so the upscale has no blocky edges.
    small = im.resize((WIDTH, h), Image.BOX).filter(ImageFilter.GaussianBlur(0.8))
    buf = io.BytesIO(); small.save(buf, 'WEBP', quality=70, method=6)
    uri = 'data:image/webp;base64,' + base64.b64encode(buf.getvalue()).decode()
    rows.append((rel, hashlib.sha256(raw).hexdigest()[:12], uri))
    print(f'{rel}: {len(uri)} chars')

out = ['// GENERATED by scripts/build-lqip.py — do not edit. Blurred placeholders for the big scene paintings (B4).',
       '// `v` = first 12 hex of the SHA-256 of the source file (tests/lqip.test.ts checks it, so a stale one fails).',
       'export const LQIP: Readonly<Record<string, { readonly v: string; readonly uri: string }>> = {']
for rel, v, uri in rows:
    out.append(f"  '{rel}': {{ v: '{v}', uri: '{uri}' }},")
out.append('};\n')
open(os.path.join(ROOT, 'src/ui/lqip.generated.ts'), 'w').write('\n'.join(out))
